// Generates an Ed25519 licence-signing key pair for development.
//   keys/license_private.pem  -> used by admin-api (never shipped)
//   apps/server/src/services/license-pubkey.ts -> embedded in the app
// Production builds replace both with the real keys from CI secrets.
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const privPath = join(root, 'keys', 'license_private.pem');
const pubTs = join(root, 'apps', 'server', 'src', 'services', 'license-pubkey.ts');

if (existsSync(privPath) && !process.argv.includes('--force')) {
  console.log(`${privPath} exists; pass --force to rotate.`);
  process.exit(0);
}

const { privateKey, publicKey } = generateKeyPairSync('ed25519');
mkdirSync(join(root, 'keys'), { recursive: true });
writeFileSync(privPath, privateKey.export({ type: 'pkcs8', format: 'pem' }));
writeFileSync(
  pubTs,
  `// Generated by scripts/dev-keys.mjs. Release builds overwrite this with the production key.\n` +
    `export const LICENSE_PUBLIC_KEY = ${JSON.stringify(publicKey.export({ type: 'spki', format: 'pem' }).toString())};\n`,
);
console.log(`wrote ${privPath}\nwrote ${pubTs}`);
